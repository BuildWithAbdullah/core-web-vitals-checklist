#!/usr/bin/env node
/* ---------------------------------------------------------------------------
   catalogue.mjs

   Writes docs/CATALOGUE.md from lib/catalogue.mjs.

   Run it with `node tools/catalogue.mjs`, not through npm. `npm run`
   prints its own banner on stdout, so a CI step that redirects the output
   into a file captures two lines of npm before the content and the
   generated file never matches the one in the repository. It passes
   locally, where the script is run directly, which is how that one survives
   review.
   --------------------------------------------------------------------------- */

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

import { findings, PHASES } from '../lib/catalogue.mjs';
import { rules } from '../lib/audit.mjs';
import { pairs } from '../lib/pairs.mjs';
import { fixtures } from '../fixtures/index.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const HEADINGS = {
  LCP: 'Largest contentful paint',
  CLS: 'Cumulative layout shift',
  INP: 'Interaction to next paint',
  METHOD: 'Whether the page can answer the question at all'
};

export function buildCatalogue() {
  const owner = new Map();
  for (const rule of rules) for (const id of rule.emits) owner.set(id, rule.id);

  const observedIn = new Map();
  const note = (id, where) => observedIn.set(id, [...(observedIn.get(id) ?? []), where]);
  for (const pair of pairs) {
    for (const id of pair.onFail) note(id, `${pair.id}/fail`);
    for (const id of pair.onPass) note(id, `${pair.id}/pass`);
  }
  for (const fixture of fixtures) {
    for (const id of fixture.expect) note(id, fixture.file);
  }

  const lines = [
    '# Finding catalogue',
    '',
    `Every finding this repository can report: ${findings.length} of them, across`,
    `${rules.length} rules.`,
    '',
    'This file is generated by `node tools/catalogue.mjs`. Edit',
    '[`lib/catalogue.mjs`](../lib/catalogue.mjs), not the tables.',
    '',
    'The third column is the one to read. A static rule reads markup and finds',
    'a shape; it has not loaded the page, it has not measured anything, and it',
    'cannot tell you whether what it found is costing a millisecond on a real',
    'visit. `test/gap.test.mjs` asserts that rather than leaving it here as a',
    'paragraph: for every finding below, the phase it names can fail to be the',
    'phase that dominates.',
    '',
    'Every finding is observed firing on a real page in CI. The last column',
    'says where, and `tools/verify.mjs` asserts that set against the catalogue',
    'in both directions, so a finding cannot sit here having never fired.',
    ''
  ];

  for (const metric of ['LCP', 'CLS', 'INP', 'METHOD']) {
    const group = findings.filter((f) => f.metric === metric);
    if (group.length === 0) continue;
    lines.push(`## ${HEADINGS[metric]}`, '');

    for (const phase of PHASES[metric]) {
      const inPhase = group.filter((f) => f.phase === phase);
      if (inPhase.length === 0) continue;
      if (PHASES[metric].length > 1) lines.push(`### Phase: ${phase}`, '');
      lines.push('| Finding | What it proves | What it does not prove | Rule | Observed on |');
      lines.push('|---|---|---|---|---|');
      for (const f of inPhase) {
        const where = (observedIn.get(f.id) ?? []).slice(0, 2).join(', ');
        lines.push(`| \`${f.id}\`<br>${f.title} | ${f.proves} | ${f.doesNotProve} | \`${owner.get(f.id)}\` | ${where} |`);
      }
      lines.push('');
    }
  }

  lines.push('## Counts', '');
  lines.push('| | |');
  lines.push('|---|---|');
  lines.push(`| Findings | ${findings.length} |`);
  lines.push(`| Rules | ${rules.length} |`);
  lines.push(`| Example pairs | ${pairs.length} |`);
  lines.push(`| Fixtures | ${fixtures.length} |`);
  lines.push('');

  return lines.join('\n');
}

const target = join(root, 'docs', 'CATALOGUE.md');

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(target, buildCatalogue());
  process.stderr.write(`Wrote docs/CATALOGUE.md\n`);
}
